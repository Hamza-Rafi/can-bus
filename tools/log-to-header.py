"""
Turn a candump log into a C header that the node can play

Usage:
python log-to-header.py reverse_light_off_attack_1.attackonly.log

This writes include/attack_log.h. Then you should rebuild and flash.
"""

import sys, re

FLASH_SIZE_LIMIT = 400 * 1024  # 4kb
CAN_LOG_LINE = re.compile(r"\((\d+\.\d+)\)\s+\S+\s+([0-9a-fA-F]+)#([0-9a-fA-F]*)\s*$")


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit("usage: log-to-header.py <log file> [output header]")

    log_path = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) == 3 else "./include/attack_log.h"

    frames = []
    for line in open(log_path):
        m = CAN_LOG_LINE.match(line.strip())
        if not m:
            continue

        time, id_text, data_text = m.groups()

        can_id = int(id_text, 16)
        data = bytes.fromhex(data_text)
        dlc = len(data)

        frames.append([float(time), can_id, dlc, data])

    size = len(frames) * 20
    if size > FLASH_SIZE_LIMIT:
        sys.exit(
            f"{len(frames)} frames need ~{size // 1024} KB, more than what fits in the flash ({FLASH_SIZE_LIMIT // 1024})"
        )

    with open(out_path, "w+") as f:
        f.write(f"// Generated by tools/log-to-header.py from {log_path}\n")
        f.write("#pragma once\n")
        f.write("#include <stdint.h>\n\n")
        f.write("struct LogFrame {\n")
        f.write("   uint32_t time_us;\n")
        f.write("   uint32_t id;\n")
        f.write("   uint8_t dlc;\n")
        f.write("   uint8_t data[8];\n")
        f.write("};\n\n")
        f.write(f"#define LOG_FRAME_COUNT {len(frames)}\n\n")
        f.write("const LogFrame log_frames[] = {\n")
        for t, id, dlc, data in frames:
            time_us = round(t * 1_000_000)
            data_bytes = ", ".join(f"0x{b:02X}" for b in data)
            if data_bytes == "":
                data_bytes = "0"

            f.write(f"{{ {time_us:10d}, 0x{id:03X}, {dlc}, {{ {data_bytes} }} }},\n")
        f.write("};\n")

    ids = sorted(set(frame[1] & 0x1FFFFFFF for frame in frames))
    id_list = " ".join(f"0x{i:03X}" for i in ids)
    duration = frames[-1][0]
    flash_kb = size // 1024 + 1

    print(f"{len(frames)} frames, {duration:.1f} s, IDs: {id_list}")
    print(f"~{flash_kb} KB of flash -> {out_path}")


if __name__ == "__main__":
    main()
